import assert from 'node:assert/strict'
import { imageUploadError,noteImages,validImageUrl,MAX_IMAGES } from '../src/imageUpload.ts'
assert.equal(imageUploadError([{type:'image/png',size:3_000_000}]),null)
for(const type of ['image/jpeg','image/webp','image/gif','image/avif','image/bmp'])assert.equal(imageUploadError([{type,size:100}]),null)
assert.match(imageUploadError([{type:'image/png',size:3_000_001}]),/too large/)
assert.match(imageUploadError([{type:'text/plain',size:100}]),/JPG/)
assert.match(imageUploadError([{type:'image/svg+xml',size:100}]),/JPG/)
assert.match(imageUploadError([]),/one or more/)
assert.equal(imageUploadError([{type:'image/png',size:1},{type:'image/png',size:1}]),null)
assert.equal(imageUploadError([{type:'image/png',size:1}],MAX_IMAGES-1),null)
assert.match(imageUploadError([{type:'image/png',size:1}],MAX_IMAGES),/12 photos/)
assert.match(imageUploadError(Array.from({length:13},()=>({type:'image/png',size:1}))),/12 photos/)
assert.deepEqual(noteImages({image:'legacy-photo'}),['legacy-photo'])
assert.deepEqual(noteImages({image:'legacy-photo',images:[]}),[])
assert.deepEqual(noteImages({image:'legacy-photo',images:['one','two']}),['one','two'])
assert.deepEqual(noteImages(JSON.parse(JSON.stringify({images:['one','two','three']}))),['one','two','three'])
assert.ok(validImageUrl('data:image/png;base64,abc'))
assert.ok(validImageUrl('data:image/avif;base64,abc'))
assert.ok(validImageUrl('data:image/bmp;base64,abc'))
assert.ok(validImageUrl('https://example.com/photo.png'))
assert.ok(!validImageUrl('javascript:alert(1)'))
console.log('Multiple image limits, legacy compatibility and JSON roundtrip checks passed')
